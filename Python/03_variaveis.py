#Variáveis são espaços na memória do computador onde podemos armazenar informações.
#Em Python, para criar uma variável, basta escolher um nome e usar o sinal de igual
# para atribuir um valor a ela. Por exemplo:



# %%
nome = "Gabriel"
print(nome)

nome = "Github"
print(nome)

# %%
resultado = 10 + 5
print(resultado)

resultado = resultado * 2
print(resultado)

resultado = resultado - 5
print(resultado)

